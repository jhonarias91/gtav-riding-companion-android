// Generates Android help resources (EN default + ES) and the typed HelpTopic catalog
// from planning/android/AYUDA_CONTEXTUAL.md. Re-run after editing that document:
//   node tools/generate-help-resources.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = join(root, '..', 'planning', 'android', 'AYUDA_CONTEXTUAL.md');
const resEn = join(root, 'app', 'src', 'main', 'res', 'values', 'strings_help.xml');
const resEs = join(root, 'app', 'src', 'main', 'res', 'values-es', 'strings_help.xml');
const kotlinOut = join(root, 'app', 'src', 'main', 'java', 'com', 'fariddroid', 'gtbikecompanion', 'ui', 'help', 'HelpTopic.kt');

const row = /^\|\s*`([a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+)`\s*\|(.*)\|(.*)\|\s*$/;
const cell = text => {
  const m = text.trim().match(/^\*\*(.+?)\*\*\s*(.*)$/s);
  if (!m) throw new Error(`Cell without **Title.**: ${text.slice(0, 60)}`);
  const clean = s => s.replace(/\*\*/g, '').replace(/`/g, '').replace(/\s+/g, ' ').trim();
  return { title: clean(m[1]).replace(/[.:]$/, ''), body: clean(m[2]) };
};
const resName = id => 'help_' + id.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/\./g, '_').toLowerCase();
const constName = id => id.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/\./g, '_').toUpperCase();
const xml = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/^([@?])/, '\\$1');
const entry = (name, value) => `    <string name="${name}"${value.includes('%') ? ' formatted="false"' : ''}>${xml(value)}</string>`;

const topics = [];
for (const line of (await readFile(source, 'utf8')).split(/\r?\n/)) {
  const m = line.match(row);
  if (!m) continue;
  topics.push({ id: m[1], en: cell(m[2]), es: cell(m[3]) });
}
if (topics.length === 0) throw new Error('No help rows found');
if (new Set(topics.map(t => t.id)).size !== topics.length) throw new Error('Duplicate helpId');

const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/generate-help-resources.mjs from planning/android/AYUDA_CONTEXTUAL.md. Do not edit. -->\n<resources>\n';
const body = lang => topics.map(t => `${entry(resName(t.id) + '_title', t[lang].title)}\n${entry(resName(t.id) + '_body', t[lang].body)}`).join('\n');
await mkdir(dirname(resEs), { recursive: true });
await mkdir(dirname(kotlinOut), { recursive: true });
await writeFile(resEn, `${header}${body('en')}\n</resources>\n`);
await writeFile(resEs, `${header}${body('es')}\n</resources>\n`);

const kt = `// GENERATED by tools/generate-help-resources.mjs from planning/android/AYUDA_CONTEXTUAL.md. Do not edit.
package com.fariddroid.gtbikecompanion.ui.help

import androidx.annotation.StringRes
import com.fariddroid.gtbikecompanion.R

/** Typed, exhaustive helpId -> local resources. The server sends ids, never help copy. */
enum class HelpTopic(val id: String, @StringRes val title: Int, @StringRes val body: Int) {
${topics.map(t => `    ${constName(t.id)}("${t.id}", R.string.${resName(t.id)}_title, R.string.${resName(t.id)}_body),`).join('\n')}
    ;

    companion object {
        /** Unknown ids from a newer bridge fall back to the generic connection help. */
        fun fromId(id: String?): HelpTopic = entries.firstOrNull { it.id == id } ?: CONNECTION_STATUS
    }
}
`;
await writeFile(kotlinOut, kt);
console.log(`Generated ${topics.length} help topics`);
